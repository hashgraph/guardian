import { CommonModule } from '@angular/common';
import { ChangeDetectorRef, NO_ERRORS_SCHEMA } from '@angular/core';
import { TestBed } from '@angular/core/testing';
import { By } from '@angular/platform-browser';
import { FormulaItemType, ISchemaDocument, Schema, SchemaDataTypes } from '@guardian/interfaces';
import { DialogService } from 'primeng/dynamicdialog';
import { ButtonModule } from 'primeng/button';
import { TooltipModule } from 'primeng/tooltip';
import { BehaviorSubject } from 'rxjs';
import { IPFSService } from 'src/app/services/ipfs.service';
import { ArtifactService } from 'src/app/services/artifact.service';
import { CsvService } from 'src/app/services/csv.service';
import { GzipService } from 'src/app/services/gzip.service';
import { IndexedDbRegistryService } from 'src/app/services/indexed-db-registry.service';
import { SchemaFormPreferencesService } from 'src/app/services/schema-form-preferences.service';
import { TableFormulaButtonComponent } from '../../common/table-dialog/table-formula-button.component';
import { TableDialogComponent } from '../../common/table-dialog/table-dialog.component';
import { FormulasViewDialog } from '../../formulas/dialogs/formulas-view-dialog/formulas-view-dialog.component';
import { FormulasTree } from '../../formulas/models/formula-tree';
import { TableViewerComponent } from '../table-viewer/table-viewer.component';
import { SchemaFormViewComponent } from './schema-form-view.component';

const SCHEMA = '#sites&1.0.0';
const columns = [{ key: 'co2', name: 'CO2' }];

function table(value: number): string {
    return JSON.stringify({ type: 'table', csv: `CO2\r\n${value}`, columnKeys: ['co2'], columnNames: ['CO2'] });
}

async function render(nested = false, tableArray = false) {
    const open = vi.fn();
    TestBed.configureTestingModule({
        declarations: [SchemaFormViewComponent, TableViewerComponent],
        imports: [CommonModule, ButtonModule, TooltipModule, TableFormulaButtonComponent],
        providers: [
            { provide: DialogService, useValue: { open } },
            { provide: IPFSService, useValue: {} },
            { provide: CsvService, useValue: new CsvService() },
            { provide: ArtifactService, useValue: {} },
            { provide: GzipService, useValue: {} },
            { provide: IndexedDbRegistryService, useValue: { clearStore: () => Promise.resolve() } },
            { provide: SchemaFormPreferencesService, useValue: { showFieldMetadata$: new BehaviorSubject(false) } },
        ],
        schemas: [NO_ERRORS_SCHEMA],
    });
    TestBed.overrideComponent(TableViewerComponent, {
        set: { providers: [{ provide: DialogService, useValue: { open } }] }
    });
    const tableField: ISchemaDocument = {
        ...(tableArray ? { type: SchemaDataTypes.array, items: { type: SchemaDataTypes.string } } : { type: SchemaDataTypes.string }),
        title: 'Site results', description: 'Site results',
        $comment: JSON.stringify({ customType: 'table', tableColumns: columns })
    };
    const siteProperties: Record<string, ISchemaDocument> = {
        site: { type: SchemaDataTypes.string, title: 'Site' }
    };
    if (nested) {
        siteProperties.metrics = { $ref: '#metrics' };
    } else {
        siteProperties.siteResults = tableField;
    }
    const schema = new Schema({ iri: SCHEMA, document: {
        $id: SCHEMA, type: SchemaDataTypes.object,
        properties: { sites: { type: SchemaDataTypes.array, items: { $ref: '#site' } } },
        $defs: {
            '#site': { $id: '#site', type: SchemaDataTypes.object, properties: siteProperties },
            '#metrics': { $id: '#metrics', type: SchemaDataTypes.object, properties: { siteResults: tableField } }
        }
    } });
    const path = nested ? 'sites.metrics.siteResults' : 'sites.siteResults';
    const values = { sites: [11, 22].map((value, index) => {
        const results = { siteResults: tableArray ? [table(11), table(22)] : table(value) };
        return { site: `S${index + 1}`, ...(nested ? { metrics: results } : results) };
    }) };
    const tree = new FormulasTree();
    tree.setFormulas([
        { autoGenerated: true, config: { formulas: ['aCo2', 'bCo2'].map((name, tableIndex) => ({
            uuid: name, name, description: '', type: FormulaItemType.Formula, value: tableIndex === 0 ? '11' : '22',
            link: { type: 'schema' as const, entityId: SCHEMA, item: path, columnKey: 'co2', rowIndex: 0, tableIndex }
        })) } },
        { config: { formulas: [{ uuid: 'manual', name: 'S2 column', description: '', type: FormulaItemType.Text,
            link: { type: 'schema', entityId: SCHEMA, item: path, columnKey: 'co2',
                condition: { field: schema.getField('sites.site')!, fieldPath: ['sites', 'site'], fieldValue: 'S2' } }
        }] } }
    ]);
    tree.update();
    const fixture = TestBed.createComponent(SchemaFormViewComponent);
    fixture.componentRef.setInput('private-fields', {});
    fixture.componentRef.setInput('schema', schema);
    fixture.componentRef.setInput('values', values);
    const sources = tree.getFields(SCHEMA, { data: values, anyEntry: true });
    for (const source of Object.values<any>(sources)) {
        source.origin = 'document';
    }
    fixture.componentRef.setInput('formulas', sources);
    fixture.detectChanges();
    await fixture.whenStable();
    const sites = fixture.componentInstance.fields![0];
    const expand: HTMLButtonElement = fixture.nativeElement.querySelector('.sf-ro-recbar-actions button');
    expand.click();
    await fixture.whenStable();
    fixture.detectChanges();
    return { fixture, sites, tree, open };
}

describe('SchemaFormViewComponent cell Fx in repeated sub-schemas', () => {
    for (const nested of [false, true]) {
        it(`opens the exact cell formula in each record${nested ? ' through an ordinary sub-schema' : ''}`, async () => {
            const { fixture, open, tree } = await render(nested);
            const tables = fixture.debugElement.queryAll(By.directive(TableViewerComponent));
            expect(tables).toHaveLength(2);
            for (const [index, view] of tables.entries()) {
                const viewer: TableViewerComponent = view.componentInstance;
                expect(viewer.tableIndex).toBe(index);
                expect(viewer.previewRowsLimited).toEqual([{ co2: index === 0 ? '11' : '22' }]);
                const button: HTMLButtonElement | null = view.nativeElement.querySelector('.table-viewer__cell--data app-table-formula-button button');
                expect(button).not.toBeNull();
                button!.click();
                const [dialog, config] = open.mock.lastCall!;
                expect(dialog).toBe(FormulasViewDialog);
                expect(config.data).toMatchObject({ columnKey: 'co2', rowIndex: 0, tableIndex: index });
                expect(tree.get(config.data.schema, config.data.path, config.data.context, config.data).map(item => item.name))
                    .toEqual([index === 0 ? 'aCo2' : 'bCo2']);
                expect(view.nativeElement.querySelectorAll('.table-viewer__cell--head app-table-formula-button button')).toHaveLength(index);
                await viewer.openDialog();
                const [tableDialog, tableConfig] = open.mock.lastCall!;
                expect(tableDialog).toBe(TableDialogComponent);
                const cell = tableConfig.data.formulaActions.cell('co2', 0);
                expect(cell).not.toBeNull();
                cell.open(new Event('click'));
                expect(open.mock.lastCall![1].data).toMatchObject({ tableIndex: index, rowIndex: 0, columnKey: 'co2' });
            }
        });
    }

    it('keeps the absolute record index after pagination', async () => {
        const { fixture, sites, open } = await render();
        fixture.componentInstance.onPage(sites, { pageIndex: 1, pageSize: 1 });
        fixture.componentRef.injector.get(ChangeDetectorRef).markForCheck();
        fixture.detectChanges();
        await fixture.whenStable();
        fixture.detectChanges();
        const tables = fixture.debugElement.queryAll(By.directive(TableViewerComponent));
        expect(tables).toHaveLength(1);
        expect(tables[0].componentInstance.tableIndex).toBe(1);
        const button: HTMLButtonElement = tables[0].nativeElement.querySelector('.table-viewer__cell--data app-table-formula-button button');
        expect(button).not.toBeNull();
        button.click();
        expect(open.mock.lastCall![1].data).toMatchObject({ tableIndex: 1, rowIndex: 0, columnKey: 'co2' });
    });

    it('keeps a table-list element index ahead of its enclosing record index', async () => {
        const { fixture, open } = await render(false, true);
        const tables = fixture.debugElement.queryAll(By.directive(TableViewerComponent));
        expect(tables).toHaveLength(4);
        for (const [position, view] of tables.entries()) {
            const index = position % 2;
            expect(view.componentInstance.tableIndex).toBe(index);
            const button: HTMLButtonElement = view.nativeElement.querySelector('.table-viewer__cell--data app-table-formula-button button');
            expect(button).not.toBeNull();
            button.click();
            expect(open.mock.lastCall![1].data).toMatchObject({ tableIndex: index, rowIndex: 0, columnKey: 'co2' });
        }
    });
});
