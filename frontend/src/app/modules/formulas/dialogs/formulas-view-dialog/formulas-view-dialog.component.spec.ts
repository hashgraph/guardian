import { FormulaItemType } from '@guardian/interfaces';
import { FormulasTree } from '../../models/formula-tree';
import { FormulasViewDialog } from './formulas-view-dialog.component';

describe('FormulasViewDialog table targets', () => {
    it('requeries only the selected cell and includes both sources for a column', () => {
        const tree = new FormulasTree();
        tree.setFormulas([false, true].map(autoGenerated => ({ autoGenerated, config: { formulas: [
            { uuid: `column-${autoGenerated}`, name: 'column', description: '', type: FormulaItemType.Formula,
                link: { type: 'schema', entityId: '#s', item: 'grid', columnKey: 'co2' } },
            { uuid: `cell-${autoGenerated}`, name: 'cell', description: '', type: FormulaItemType.Formula,
                link: { type: 'schema', entityId: '#s', item: 'grid', columnKey: 'co2', rowIndex: 0 } },
            { uuid: `other-${autoGenerated}`, name: 'other', description: '', type: FormulaItemType.Formula,
                link: { type: 'schema', entityId: '#s', item: 'grid', columnKey: 'net' } }
        ] } })));
        tree.update();
        const data = { tree, schema: '#s', path: 'grid', columnKey: 'co2', origin: 'document' };
        const column = new FormulasViewDialog({} as any, { data } as any, {} as any, {} as any);
        column.ngOnInit();
        expect(column.items.map(item => item.uuid)).toEqual(['column-false', 'column-true']);
        const cell = new FormulasViewDialog({} as any, { data: { ...data, rowIndex: 0 } } as any, {} as any, {} as any);
        cell.ngOnInit();
        expect(cell.items.map(item => item.uuid)).toEqual(['cell-false', 'cell-true']);
    });
});
