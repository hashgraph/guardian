import { FormulaItemType } from '@guardian/interfaces';
import { FormulasTree } from './formula-tree';
import { TableFormulas } from './table-formulas';

describe('TableFormulas', () => {
    it('opens both sources for the selected declared column with the current condition context', () => {
        const tree = new FormulasTree();
        tree.setFormulas([false, true].map(autoGenerated => ({ autoGenerated, config: { formulas: [{
            uuid: String(autoGenerated), name: 'co2', description: '', type: FormulaItemType.Formula,
            link: { type: 'schema', entityId: '#s', item: 'table', columnKey: 'co2' }
        }] } })));
        tree.update();
        const context = { data: { mode: 'ready' } };
        const open = vi.fn();
        const actions = new TableFormulas(() => ({ tree, schema: '#s', path: 'table', context, origin: 'document' }),
            [{ key: 'co2', name: 'CO2' }], open);
        expect(actions.column('missing')).toBeNull();
        const action = actions.column('co2')!;
        expect(actions.column('co2')).toBe(action);
        action.open(new Event('click'));
        expect(open).toHaveBeenCalledWith(expect.objectContaining({ columnKey: 'co2', context, origin: 'document' }));
        expect(tree.get('#s', 'table', context, { columnKey: 'co2' })).toHaveLength(2);
        expect(new TableFormulas(() => ({ tree, schema: '#s', path: 'table' }), [], open).column('co2')).toBeNull();
    });
});
