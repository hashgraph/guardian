import { IFormula, FormulaItemType } from '@guardian/interfaces';
import { FormulasTree } from './formula-tree';
import { FormFormulas } from './form-formulas';

const SCHEMA = '#schema-1';

function pred(name: string, value: any, fieldPath?: string[]): any {
    return {
        field: { name, type: 'string', isArray: false, isRef: false },
        fieldValue: value,
        ...(fieldPath ? { fieldPath } : {})
    };
}

function formula(uuid: string, items: any[], autoGenerated = false): IFormula {
    return {
        uuid,
        name: uuid,
        description: '',
        autoGenerated,
        config: { formulas: items, files: [] }
    };
}

function item(uuid: string, path: string, condition?: any): any {
    return {
        uuid,
        name: uuid,
        description: '',
        type: FormulaItemType.Formula,
        value: 'x=1',
        link: {
            type: 'schema',
            entityId: SCHEMA,
            item: path,
            ...(condition ? { condition } : {})
        },
        relationships: []
    };
}

function buildTree(formulas: IFormula[], options?: { excludeAutoGenerated?: boolean }): FormulasTree {
    return FormulasTree.from({
        formulas,
        schemas: [],
        document: null as any,
        relationships: []
    }, options)!;
}

describe('FormFormulas', () => {
    it('shows unconditional items regardless of data', () => {
        const tree = buildTree([formula('f1', [item('a', 'field1')])]);
        const model = new FormFormulas(tree, SCHEMA);
        model.setData({});
        expect(model.get(`${SCHEMA}/field1`).map((e) => e.uuid)).toEqual(['a']);
    });

    it('returns an empty list for unknown fields', () => {
        const tree = buildTree([formula('f1', [item('a', 'field1')])]);
        const model = new FormFormulas(tree, SCHEMA);
        expect(model.get(`${SCHEMA}/other`)).toEqual([]);
    });

    it('toggles visibility when the data changes', () => {
        const tree = buildTree([formula('f1', [
            item('a', 'field1', pred('mode', 'A')),
            item('b', 'field1', pred('mode', 'B'))
        ])]);
        const model = new FormFormulas(tree, SCHEMA);
        const key = `${SCHEMA}/field1`;

        model.setData({ mode: 'A' });
        expect(model.get(key).map((e) => e.uuid)).toEqual(['a']);

        model.setData({ mode: 'B' });
        expect(model.get(key).map((e) => e.uuid)).toEqual(['b']);

        model.setData({ mode: 'C' });
        expect(model.get(key).length).toBe(0);
    });

    it('keeps the same array reference while the data is unchanged', () => {
        const tree = buildTree([formula('f1', [item('a', 'field1', pred('mode', 'A'))])]);
        const model = new FormFormulas(tree, SCHEMA);
        const key = `${SCHEMA}/field1`;
        model.setData({ mode: 'A' });
        const first = model.get(key);
        expect(model.get(key)).toBe(first);
        model.setData({ mode: 'A' });
        expect(model.get(key)).not.toBe(first);
        expect(model.get(key).map((e) => e.uuid)).toEqual(['a']);
    });

    it('scopes array paths by entry index', () => {
        const condition = pred('kind', 'x', ['rows', 'kind']);
        const tree = buildTree([formula('f1', [item('a', 'field1', condition)])]);
        const model = new FormFormulas(tree, SCHEMA);
        const key = `${SCHEMA}/field1`;
        model.setData({ rows: [{ kind: 'y' }, { kind: 'x' }] });

        expect(model.get(key, { rows: 0 }).length).toBe(0);
        expect(model.get(key, { rows: 1 }).map((e) => e.uuid)).toEqual(['a']);
    });

    it('matches any entry when no entry index is given', () => {
        const condition = pred('kind', 'x', ['rows', 'kind']);
        const tree = buildTree([formula('f1', [item('a', 'field1', condition)])]);
        const model = new FormFormulas(tree, SCHEMA);
        const key = `${SCHEMA}/field1`;

        model.setData({ rows: [{ kind: 'y' }, { kind: 'x' }] });
        expect(model.get(key).map((e) => e.uuid)).toEqual(['a']);

        model.setData({ rows: [{ kind: 'y' }] });
        expect(model.get(key).length).toBe(0);
    });

    it('supports AND and OR display conditions', () => {
        const tree = buildTree([formula('f1', [
            item('and', 'field1', { AND: [pred('a', 1), pred('b', 2)] }),
            item('or', 'field1', { OR: [pred('a', 1), pred('b', 2)] })
        ])]);
        const model = new FormFormulas(tree, SCHEMA);
        const key = `${SCHEMA}/field1`;

        model.setData({ a: 1, b: 0 });
        expect(model.get(key).map((e) => e.uuid)).toEqual(['or']);
        model.setData({ a: 1, b: 2 });
        expect(model.get(key).map((e) => e.uuid)).toEqual(['and', 'or']);
    });

    it('uses the supplied equality function', () => {
        const tree = buildTree([formula('f1', [item('a', 'field1', pred('mode', 'ABC'))])]);
        const model = new FormFormulas(tree, SCHEMA, (a, b) => String(a).toLowerCase() === String(b).toLowerCase());
        model.setData({ mode: 'abc' });
        expect(model.get(`${SCHEMA}/field1`).length).toBe(1);
    });
});

describe('FormulasTree filtering', () => {
    const auto = formula('auto', [item('auto-item', 'field1')], true);
    const manual = formula('manual', [item('manual-item', 'field1')]);

    it('excludes auto-generated formulas when requested', () => {
        const tree = buildTree([auto, manual], { excludeAutoGenerated: true });
        expect(tree.get(SCHEMA, 'field1').map((e) => e.uuid)).toEqual(['manual-item']);
    });

    it('keeps auto-generated formulas by default', () => {
        const tree = buildTree([auto, manual]);
        expect(tree.get(SCHEMA, 'field1').map((e) => e.uuid)).toEqual(['auto-item', 'manual-item']);
    });

    it('getFields omits fields without visible items for a context', () => {
        const tree = buildTree([formula('f1', [
            item('a', 'field1', pred('mode', 'A')),
            item('b', 'field2')
        ])]);
        expect(Object.keys(tree.getFields(SCHEMA)).sort()).toEqual([`${SCHEMA}/field1`, `${SCHEMA}/field2`]);
        expect(Object.keys(tree.getFields(SCHEMA, { data: { mode: 'B' } }))).toEqual([`${SCHEMA}/field2`]);
        expect(Object.keys(tree.getFields(SCHEMA, { data: { mode: 'A' } })).sort())
            .toEqual([`${SCHEMA}/field1`, `${SCHEMA}/field2`]);
    });

    it('get without a context shows every item', () => {
        const tree = buildTree([formula('f1', [item('a', 'field1', pred('mode', 'A'))])]);
        expect(tree.get(SCHEMA, 'field1').length).toBe(1);
        expect(tree.get(SCHEMA, 'field1', { data: {} }).length).toBe(0);
    });
});


describe('FormFormulas with several links', () => {
    function multi(uuid: string, links: { path: string, condition?: any }[]): any {
        return {
            uuid,
            name: uuid,
            description: '',
            type: FormulaItemType.Formula,
            value: 'x=1',
            links: links.map((e) => ({
                type: 'schema',
                entityId: SCHEMA,
                item: e.path,
                ...(e.condition ? { condition: e.condition } : {})
            })),
            relationships: []
        };
    }

    function build(items: any[]): FormFormulas {
        return new FormFormulas(buildTree([formula('f', items)]), SCHEMA);
    }

    it('reads an item saved with link only', () => {
        const forms = build([item('old', 'a')]);
        forms.setData({});
        expect(forms.get(`${SCHEMA}/a`).map((e) => e.uuid)).toEqual(['old']);
    });

    it('shows the item on every field it links to', () => {
        const forms = build([multi('m', [{ path: 'a' }, { path: 'b' }])]);
        forms.setData({});
        expect(forms.get(`${SCHEMA}/a`).map((e) => e.uuid)).toEqual(['m']);
        expect(forms.get(`${SCHEMA}/b`).map((e) => e.uuid)).toEqual(['m']);
    });

    it('applies the condition of a link only to its own field', () => {
        const forms = build([multi('m', [{ path: 'a', condition: pred('kind', 'x') }, { path: 'b' }])]);
        forms.setData({ kind: 'y' });
        expect(forms.get(`${SCHEMA}/a`)).toEqual([]);
        expect(forms.get(`${SCHEMA}/b`).map((e) => e.uuid)).toEqual(['m']);
        forms.setData({ kind: 'x' });
        expect(forms.get(`${SCHEMA}/a`).map((e) => e.uuid)).toEqual(['m']);
    });

    it('shows the item when any link to the field passes', () => {
        const forms = build([multi('m', [
            { path: 'a', condition: pred('kind', 'x') },
            { path: 'a', condition: pred('kind', 'y') }
        ])]);
        forms.setData({ kind: 'y' });
        expect(forms.get(`${SCHEMA}/a`).map((e) => e.uuid)).toEqual(['m']);
        forms.setData({ kind: 'z' });
        expect(forms.get(`${SCHEMA}/a`)).toEqual([]);
    });

    it('lists the item once for two links to one field', () => {
        const forms = build([multi('m', [{ path: 'a' }, { path: 'a' }])]);
        forms.setData({});
        expect(forms.get(`${SCHEMA}/a`).length).toBe(1);
    });

    it('detects the conditions per field', () => {
        const forms = build([multi('m', [{ path: 'a', condition: pred('kind', 'x') }, { path: 'b' }])]);
        expect(forms.hasConditions).toBe(true);
        expect(build([multi('m', [{ path: 'a' }, { path: 'b' }])]).hasConditions).toBe(false);
    });

    it('omits a field from getFields when none of its links passes', () => {
        const tree = buildTree([formula('f', [multi('m', [{ path: 'a', condition: pred('kind', 'x') }, { path: 'b' }])])]);
        const keys = Object.keys(tree.getFields(SCHEMA, { data: { kind: 'y' }, anyEntry: true }));
        expect(keys).toEqual([`${SCHEMA}/b`]);
    });
});

describe('FormFormulas of a drilled-into sub-schema', () => {
    const SUB = '#sub-schema';
    const tree = () => buildTree([formula('f', [
        item('a', 'nested.summary'),
        item('b', 'nested.deep.value'),
        item('c', 'other.summary')
    ])]);

    it('resolves links stored under the document schema by the drill path', () => {
        const model = new FormFormulas(tree(), SUB, undefined, { schema: SCHEMA, prefix: ['nested'] });
        expect(model.get(`${SUB}/summary`).map((i) => i.uuid)).toEqual(['a']);
        expect(model.get(`${SUB}/deep.value`).map((i) => i.uuid)).toEqual(['b']);
    });

    it('ignores links of other branches and the document schema paths', () => {
        const model = new FormFormulas(tree(), SUB, undefined, { schema: SCHEMA, prefix: ['nested'] });
        expect(model.get(`${SUB}/other.summary`)).toEqual([]);
        expect(model.get(`${SCHEMA}/nested.summary`)).toEqual([]);
    });

    it('keeps the plain lookup without a link scope', () => {
        const model = new FormFormulas(tree(), SCHEMA);
        expect(model.get(`${SCHEMA}/nested.summary`).map((i) => i.uuid)).toEqual(['a']);
    });

    it('evaluates display conditions against the document, not the sub-form', () => {
        const conditional = buildTree([formula('f', [
            item('a', 'nested.summary', pred('flag', 'on', ['nested', 'flag'])),
            item('b', 'nested.summary', pred('flag', 'on'))
        ])]);
        const model = new FormFormulas(conditional, SUB, undefined, { schema: SCHEMA, prefix: ['nested'] });
        model.setData({ flag: 'off' });
        expect(model.get(`${SUB}/summary`)).toEqual([]);
        model.setData({ flag: 'on' });
        expect(model.get(`${SUB}/summary`).map((i) => i.uuid)).toEqual(['a']);
    });

    it('prefixes array entry keys with the drill path', () => {
        const conditional = buildTree([formula('f', [
            item('a', 'nested.row.value', pred('kind', 'x', ['nested', 'row', 'kind']))
        ])]);
        const model = new FormFormulas(conditional, SUB, undefined, { schema: SCHEMA, prefix: ['nested'] });
        model.setData({ row: [{ kind: 'y' }, { kind: 'x' }] });
        expect(model.get(`${SUB}/row.value`, { row: 0 })).toEqual([]);
        expect(model.get(`${SUB}/row.value`, { row: 1 }).map((i) => i.uuid)).toEqual(['a']);
    });
});
